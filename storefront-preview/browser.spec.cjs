const {test,expect}=require('@playwright/test');
const fs=require('node:fs');
const path=require('node:path');
test('browse the complete read-only storefront',async({page},testInfo)=>{
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{level:1})).toContainText('BUILT FOR');
  const screenshots=path.join(__dirname,'screenshots');
  fs.mkdirSync(screenshots,{recursive:true});
  const capture=async name=>{
    await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:path.join(screenshots,`${testInfo.project.name}-${name}.png`),fullPage:true});
  };
  await capture('home');
  if(testInfo.project.name==='mobile'){
    await page.getByRole('button',{name:'Menu'}).click();
    await expect(page.getByRole('button',{name:'Menu'})).toHaveAttribute('aria-expanded','true');
    await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Explore parts'}).click();
    await expect(page.getByRole('button',{name:'Menu'})).toHaveAttribute('aria-expanded','false');
  }else await page.getByRole('link',{name:'Explore the catalog',exact:true}).click();
  await expect(page.locator('.product-card')).toHaveCount(12);
  await page.getByLabel('Search parts or platforms').fill('senton');
  await page.getByRole('button',{name:'Electronics',exact:true}).click();
  await expect(page.locator('.product-card')).toHaveCount(1);
  await page.reload();
  await expect(page.getByLabel('Search parts or platforms')).toHaveValue('senton');
  await expect(page.locator('.product-card')).toHaveCount(1);
  await page.getByLabel('Search parts or platforms').fill('unfindable-part');
  await expect(page.getByRole('heading',{name:'No parts match this search.'})).toBeVisible();
  await page.getByRole('button',{name:'Clear filters'}).click();
  await expect(page.locator('.product-card')).toHaveCount(12);
  await page.getByLabel('Sort by').selectOption('az');
  await capture('catalog');
  await page.locator('.product-card a').first().click();
  await expect(page.getByText('Preview only — not available to order',{exact:true})).toBeVisible();
  await page.getByText('Fitment and specifications',{exact:true}).click();
  await expect(page.getByText(/Before ordering becomes available/)).toBeVisible();
  await capture('product');
  await page.reload();
  await expect(page.getByText('Preview only — not available to order',{exact:true})).toBeVisible();
  await page.goto('/#/garage');
  await expect(page.locator('.build-card')).toHaveCount(2);
  await capture('garage');
  await page.getByRole('link').filter({has:page.getByRole('heading',{name:'Senton Reforged',exact:true})}).click();
  await expect(page.locator('.journal li')).toHaveCount(4);
  await capture('build');
  await page.goto('/#/product/missing');
  await expect(page.getByText('Page not found',{exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});
